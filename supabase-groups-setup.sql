-- ============================================================
--  账户分组系统 - 数据库建表 SQL
--  执行前请备份数据，仅新增表/字段，不修改旧数据
-- ============================================================

-- 1. 新建分组表
CREATE TABLE IF NOT EXISTS workbench_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. users 表新增字段（分组ID + 申请状态）
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'workbench_users' AND column_name = 'group_id'
  ) THEN
    ALTER TABLE workbench_users ADD COLUMN group_id BIGINT
      REFERENCES workbench_groups(id) ON DELETE SET NULL;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'workbench_users' AND column_name = 'apply_status'
  ) THEN
    ALTER TABLE workbench_users ADD COLUMN apply_status TEXT DEFAULT 'approved';
  END IF;
END $$;

-- 3. 开启 RLS（如果之前已开启可跳过）
ALTER TABLE workbench_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE workbench_users ENABLE ROW LEVEL SECURITY;

-- 4. RLS 策略（允许所有已认证用户操作，业务层做权限控制）
DROP POLICY IF EXISTS "groups_all" ON workbench_groups;
CREATE POLICY "groups_all" ON workbench_groups
  FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "users_all" ON workbench_users;
CREATE POLICY "users_all" ON workbench_users
  FOR ALL USING (true) WITH CHECK (true);

